def connect(ui, client):
    page, _, _, _, _ = ui
    snapshots, requests = {}, []
    state = {"stale": False}
    def bridge(route):
        request = route.request
        path = urlsplit(request.url).path
        target = path + ("?" + urlsplit(request.url).query if urlsplit(request.url).query else "")
        requests.append((request.method, path, request.post_data_json if request.method == "POST" else None))
        if state["stale"] and path in snapshots:
            route.fulfill(status=200, json=snapshots[path])
            return
        response = client.request(request.method, target, json=request.post_data_json if request.method == "POST" else None)
        if request.method == "GET" and response.status_code == 200:
            snapshots.setdefault(path, deepcopy(response.json()))
        route.fulfill(status=response.status_code, json=response.json())
    page.route("**/api/monitor/**", bridge)
    page.route("**/api/negotiation/groups/*/sending", bridge)
    page.route("**/api/negotiation/updates?*", lambda route: route.fulfill(status=503, json={"ok": False, "hint": "synthetic stream disconnect"}))
    return state, requests


def open_monitor(ui):
    page, url, _, _, _ = ui
    page.clock.install()
    page.goto(url + "/#/monitor?bond=SYN-A")
    expect(page.locator(".rb-card")).to_have_count(2)
    card = page.locator(".rb-card").filter(has_text="独立验收A券")
    expect(card.locator(".rb-body")).to_be_visible()
    return page, card


def refresh(page):
    with page.expect_response(lambda response: urlsplit(response.url).path == "/api/monitor/counterparties"):
        page.clock.run_for(3500)


def test_raw_is_visible_before_facts_and_same_message_updates_without_duplication(ui, v22_api):
    app, client, _, message_id = v22_api
    connect(ui, client)
    page, card = open_monitor(ui)
    message = page.locator('.msg[data-message-id="' + message_id + '"]')
    expect(message).to_have_count(1)
    expect(message).to_contain_text("原文已接收 · 解析中")
    expect(card.get_by_test_id("analysis-pending")).to_be_visible()
    expect(card.locator('[data-side="ofr"] [data-field="price"]')).to_have_text("—")
    app.state.negotiation_engine.run_once()
    refresh(page)
    expect(message).to_have_count(1)
    expect(message).to_contain_text("已分析")
    expect(message).to_contain_text("独立验收A券")
    expect(message).to_contain_text("独立验收B券")
    expect(card.get_by_test_id("analysis-pending")).to_have_count(0)
    expect(card.locator('[data-side="ofr"] [data-field="price"]')).to_have_text("3.10%")
    expect(card.locator('[data-side="ofr"] [data-field="volume"]')).to_have_text("500 万")
    expect(card.locator('[data-side="ofr"] [data-field="validity"]')).to_have_text("当日有效")


def test_stale_projection_after_reconnect_cannot_erase_new_quote_or_analysis(ui, v22_api):
    app, client, _, message_id = v22_api
    controls, _ = connect(ui, client)
    page, card = open_monitor(ui)
    expect(page.locator('.msg[data-message-id="' + message_id + '"]')).to_contain_text("解析中")
    app.state.negotiation_engine.run_once()
    refresh(page)
    expect(card.locator('[data-side="ofr"] [data-field="price"]')).to_have_text("3.10%")
    controls["stale"] = True
    refresh(page)
    expect(card.locator('[data-side="ofr"] [data-field="price"]')).to_have_text("3.10%")
    expect(page.locator('.msg[data-message-id="' + message_id + '"]')).to_contain_text("已分析")
    expect(page.locator(".hero-note")).to_contain_text("连接中断，正在补拉")


def test_stop_a_uses_group_endpoint_and_preserves_b_sending(ui, v22_api):
    app, client, groups, _ = v22_api
    _, requests = connect(ui, client)
    page, card = open_monitor(ui)
    card.get_by_role("button", name="主动撤价", exact=True).click()
    expect(card.locator(".stage")).to_have_text("已暂停")
    a = app.state.repository.group(OWNER, groups["SYN-A"]["group_id"])
    b = app.state.repository.group(OWNER, groups["SYN-B"]["group_id"])
    assert a["send_allowed"] == 0 and b["send_allowed"] == 1
    posts = [r for r in requests if r[0] == "POST"]
    assert posts == [("POST", "/api/negotiation/groups/" + a["group_id"] + "/sending", {"allowed": False})]
    expect(page.locator(".rb-card").filter(has_text="独立验收B券").locator(".stage")).to_have_text("询价中")
