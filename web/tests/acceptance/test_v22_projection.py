class Flows:
    def analyze(self, context):
        scopes, observations = {}, []
        for message in context["messages"]:
            members = [p for p in context["members"] if p["bond_code"] in message["text"]]
            scopes[message["message_id"]] = [p["member_id"] for p in members]
            for member in members:
                value, volume = ("3.10", "500") if member["bond_code"] == "SYN-A" else ("3.15", "800")
                segment = member["bond_code"] + " " + value + "出" + volume + "万"
                changes = {"price": Price("YIELD", value).dump(), "volume_wan": volume,
                           "confirmed_day": "2026-10-17", "validity": "ACTIVE", "finality": "NEGOTIABLE"}
                observations.append({"member_id": member["member_id"], "side": "ofr", "changes": changes,
                    "evidence": {key: [message["message_id"]] for key in changes},
                    "segments": [{"message_id": message["message_id"], "text": segment}],
                    "interpretation": {"quote_owner": "COUNTERPARTY", "intent": "QUOTE",
                        "negotiation_space": "NEGOTIABLE", "reason": "合成对手直接报价，尚未表明最终不能改善。"}})
        return {"schema_version": "2.2", "scopes": scopes, "observations": observations, "unresolved": {}}

    def decide(self, context):
        return {"schema_version": "2.2", "action": "WAIT", "proposal": None}


