"""Generate and check the reviewable OceanBase MySQL-mode DDL.

Source of truth: server.schema.statements(mysql=True). This exporter never
connects to a database, handles credentials, or modifies a running service.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
# Both source-tree execution and packaged app/server are supported.
module_dir = ROOT / 'app' if (ROOT / 'app' / 'server' / 'schema.py').is_file() else ROOT
sys.path.insert(0, str(module_dir))
from server.schema import statements, TABLES

SQL_FILE = ROOT / "sql" / "oceanbase" / "001_xunjia_schema_mysql.sql"

HEADER = """-- Xunjia Agent / OceanBase CE (MySQL-compatible tenant) business schema
-- Deterministically generated by scripts/export_oceanbase_schema.py.
-- AUTHORITATIVE SOURCE: server/schema.py -> statements(mysql=True)
--
-- DBA PRECONDITIONS:
--   1. Provision and explicitly select a dedicated xunjia_* database.
--   2. Verify SELECT VERSION() identifies OceanBase and
--      SHOW VARIABLES LIKE 'ob_compatibility_mode' returns MYSQL.
--   3. Approve this DDL and the application's minimal table/index privileges.
--
-- This file intentionally contains no CREATE DATABASE / DROP / USE / GRANT,
-- passwords, connection settings, or customer data. It only creates the
-- Current V2.2 application tables and their original inline indexes.
-- CREATE TABLE IF NOT EXISTS supports a first install. It does NOT migrate
-- existing schema revisions or validate columns on pre-existing tables.
-- Use a reviewed migration plan for upgrades; never silently overwrite.
"""


def render() -> str:
    original = statements(mysql=True)
    if len(original) != len(TABLES):
        raise ValueError("Unexpected change in the business table count")
    tables = []
    for sql in original:
        match = re.match(r"^CREATE TABLE IF NOT EXISTS (\w+)\s*\(", sql)
        if not match:
            raise ValueError("Unexpected DDL statement form")
        tables.append(match.group(1))
        if not sql.endswith("ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin"):
            raise ValueError("Unexpected SQL engine, encoding or collation")
        if ";" in sql:
            raise ValueError("Embedded semicolon in generated DDL")
    if tuple(tables) != TABLES:
        raise ValueError("Unexpected table identity/order")
    return HEADER + "\n" + "\n\n".join(sql + ";" for sql in original) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--write", action="store_true", help="Regenerate the checked-in SQL file")
    action.add_argument("--check", action="store_true", help="Verify SQL and schema source match (default)")
    args = parser.parse_args()
    expected = render()
    if args.write:
        SQL_FILE.parent.mkdir(parents=True, exist_ok=True)
        SQL_FILE.write_text(expected, encoding="utf-8", newline="\n")
        print("WROTE", SQL_FILE, "TABLES", len(TABLES))
        return
    if not SQL_FILE.is_file() or SQL_FILE.read_text(encoding="utf-8") != expected:
        raise SystemExit("Schema SQL is missing or differs from server.schema; regenerate with --write")
    print("PASS source-to-SQL drift check:",len(TABLES),"V2.2 tables")


if __name__ == "__main__":
    main()
